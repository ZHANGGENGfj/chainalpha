const now = Date.now();
const isoAgo = (minutes) => new Date(now - minutes * 60_000).toISOString();

function timeline(id, minutesAgo, title, summary, status = "confirmed") {
  return {id: `${id}-timeline-${minutesAgo}`, occurredAt: isoAgo(minutesAgo), title, summary, status};
}

function event(input) {
  const {
    id, minutesAgo, title, category, factSummary, importanceReason,
    impactDirection, impactHorizon = "short_term", status = "confirmed",
    sectors = [], concepts = [], companies = [], sourceCount = 3,
    updateCount = 1, importanceScore = 70, confidenceScore = 75,
    timeline: eventTimeline = [],
  } = input;
  return {
    id,
    title,
    category,
    occurredAt: isoAgo(minutesAgo),
    firstSeenAt: isoAgo(Math.max(1, minutesAgo - 2)),
    updatedAt: isoAgo(Math.max(0, minutesAgo - Math.min(updateCount * 2, minutesAgo))),
    factSummary,
    importanceReason,
    impactDirection,
    impactHorizon,
    status,
    sectors,
    concepts,
    companies,
    sourceCount,
    updateCount,
    importanceScore,
    confidenceScore,
    sourceUrl: "https://example.com/mock-event",
    timeline: eventTimeline.length
      ? eventTimeline
      : [
          timeline(id, minutesAgo, "首次发现", factSummary, "unverified"),
          timeline(id, Math.max(0, minutesAgo - 3), "交叉核验", `已完成 ${sourceCount} 个公开来源的相互核对。`, status),
        ],
  };
}

